import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const manifestPath = resolve(root, 'src/app/features/packages/package-manifest.ts');
const outputPath = resolve(root, 'src/generated/package-meta.generated.ts');
const manifestSource = await readFile(manifestPath, 'utf8');
const entryPattern = /\bid\s*:\s*['"]([^'"]+)['"]\s*,\s*name\s*:\s*['"]([^'"]+)['"]/g;
const entries = [...manifestSource.matchAll(entryPattern)].map(([, id, name]) => ({ id, name }));
const declaredEntryCount = [...manifestSource.matchAll(/\bid\s*:/g)].length;

if (entries.length === 0 || entries.length !== declaredEntryCount) {
  throw new Error(`Could not read every package id/name from ${manifestPath}`);
}
if (new Set(entries.map(({ id }) => id)).size !== entries.length) {
  throw new Error(`Duplicate package id in ${manifestPath}`);
}

function riviniaDependencies(dependencies = {}) {
  return Object.fromEntries(
    Object.entries(dependencies)
      .filter(([name]) => name.startsWith('@rivinia/'))
      .sort(([first], [second]) => first.localeCompare(second)),
  );
}

const metadata = {};
for (const { id, name } of entries) {
  const packagePath = resolve(root, 'node_modules', name, 'package.json');
  let pkg;
  try {
    pkg = JSON.parse(await readFile(packagePath, 'utf8'));
  } catch (error) {
    if (error?.code === 'ENOENT') {
      throw new Error(`Missing installed package manifest for ${name}: ${packagePath}`);
    }
    throw error;
  }
  if (pkg.name !== name || typeof pkg.version !== 'string' || typeof pkg.description !== 'string') {
    throw new Error(
      `Installed package metadata is incomplete or mismatched for ${name}: ${packagePath}`,
    );
  }

  const exports = pkg.exports && typeof pkg.exports === 'object' ? pkg.exports : {};
  const entryPoints = Object.keys(exports)
    .filter((subpath) => subpath !== './package.json')
    .map((subpath) => (subpath === '.' ? name : `${name}${subpath.slice(1)}`));

  metadata[id] = {
    name: pkg.name,
    version: pkg.version,
    description: pkg.description,
    entryPoints,
    hasUi: Object.hasOwn(exports, './ui'),
    dependencies: riviniaDependencies(pkg.dependencies),
    peerDependencies: riviniaDependencies(pkg.peerDependencies),
  };
}

const output = `// Generated by scripts/generate-package-meta.mjs. Do not edit.\nexport const PACKAGE_METADATA = ${JSON.stringify(metadata, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== output) throw new Error(`Package metadata is stale: ${outputPath}`);
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output);
}
