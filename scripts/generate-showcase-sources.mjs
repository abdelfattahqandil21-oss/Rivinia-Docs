import { readFile, writeFile } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import prettier from 'prettier';

const root = resolve(import.meta.dirname, '..');
const examples = ['select', 'datepicker', 'table', 'modal', 'toast'];
for (const name of examples) {
  const folder = resolve(root, 'src/app/features/showcase/demos', name);
  const tsPath = resolve(folder, `${name}-example.component.ts`);
  const htmlPath = resolve(folder, `${name}-example.component.html`);
  const cssPath = resolve(folder, `${name}-example.component.css`);
  const outputPath = resolve(
    root,
    'src/app/pages/home/showcase/examples/generated',
    `${name}-example.source.generated.ts`,
  );
  const payload = {
    html: await readFile(htmlPath, 'utf8'),
    typescript: await readFile(tsPath, 'utf8'),
    css: await readFile(cssPath, 'utf8'),
  };
  payload.typescript = payload.typescript.replace(
    /\b(templateUrl|styleUrl)\s*:\s*(['"])([^'"]+)\2/g,
    (_, property, quote, assetPath) => `${property}: ${quote}./${basename(assetPath)}${quote}`,
  );

  const lines = payload.typescript.split(/\r?\n/);
  for (let index = 0; index < lines.length; index += 1) {
    if (!/^\s*import\b/.test(lines[index])) continue;
    let statement = lines[index];
    while (!statement.includes(';') && index + 1 < lines.length) {
      statement += `\n${lines[++index]}`;
    }
    const specifier =
      /\bfrom\s*['"]([^'"]+)['"]/.exec(statement)?.[1] ??
      /^\s*import\s*['"]([^'"]+)['"]/.exec(statement)?.[1];
    if (specifier?.startsWith('.')) {
      throw new Error(`Displayed demo source contains app-local import "${specifier}": ${tsPath}`);
    }
  }
  for (const match of payload.typescript.matchAll(/\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g)) {
    if (match[1].startsWith('.')) {
      throw new Error(`Displayed demo source contains app-local import "${match[1]}": ${tsPath}`);
    }
  }

  const output = await prettier.format(
    `// Generated by scripts/generate-showcase-sources.mjs. Do not edit.\nexport const ${name}ExampleSource = ${JSON.stringify(payload, null, 2)} as const;\n`,
    { ...(await prettier.resolveConfig(outputPath)), filepath: outputPath },
  );
  if (process.argv.includes('--check')) {
    const current = await readFile(outputPath, 'utf8').catch(() => '');
    if (current !== output) throw new Error(`Showcase source is stale: ${outputPath}`);
  } else {
    await writeFile(outputPath, output);
  }
}
